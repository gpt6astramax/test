// Copies the built web app (depth-music/public, with its app-manifest.json) into snapshot.js: the version of the page
// the app ships with, shown on the very first launch, offline. Run it before building the app for a store, so new
// installs start from a recent page (they would otherwise fetch the difference in the background on the first launch):
//
//   cd depth-music/app && npm run build && cd ../shell && npm run snapshot
//
// Day-to-day changes to the page need none of this: deploy the web app as usual, and the app picks them up itself.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isText } from '../web/assemble.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const pub = path.resolve(here, '..', '..', 'public');
const manifest = JSON.parse(fs.readFileSync(path.join(pub, 'app-manifest.json'), 'utf8'));
const files = {};
for (const f of manifest.files) {
  const buf = fs.readFileSync(path.join(pub, f.path));
  files[f.sha256] = isText(f.path) ? buf.toString('utf8') : buf.toString('base64');
}
const out = `// Generated by scripts/snapshot.mjs from depth-music/public (version ${manifest.version}, built ${manifest.built}). Do not edit.\n` +
  `export default ${JSON.stringify({ manifest, files })};\n`;
fs.writeFileSync(path.join(here, '..', 'snapshot.js'), out);
console.log(`snapshot.js: version ${manifest.version}, ${(out.length / 1024).toFixed(0)} KB`);
