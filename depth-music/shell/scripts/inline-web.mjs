// Bakes the built web app (../public) into one self-contained HTML document, written to web.js, which the app hands
// straight to its WebView. Script, styles and fonts are all inside it, so the app shows the page at once, with no
// network, from the very first launch: it ships inside the app. Run after building the web app:
//
//   cd depth-music/app && npm run build && cd ../shell && node scripts/inline-web.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pub = path.resolve(here, '..', '..', 'public');
let html = fs.readFileSync(path.join(pub, 'index.html'), 'utf8');
const read = (rel) => fs.readFileSync(path.join(pub, rel.replace(/^\.\//, '')));

// styles: inline, with their fonts as data URLs
html = html.replace(/<link rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g, (m, href) => {
  const dir = path.dirname(href);
  const css = read(href).toString('utf8').replace(/url\((\.\/[^)]+\.woff2)\)/g, (u, font) =>
    `url(data:font/woff2;base64,${read(path.join(dir, font)).toString('base64')})`);
  return `<style>${css}</style>`;
});
// the script: inline (a "</script" inside it would end the element early)
html = html.replace(/<script type="module"[^>]*src="([^"]+)"[^>]*><\/script>/g, (m, src) =>
  `<script type="module">${read(src).toString('utf8').replace(/<\/script/gi, '<\\/script')}</script>`);
// icons only matter to a browser's tab and home screen
html = html.replace(/<link rel="(apple-touch-icon|icon)"[^>]*>\n?/g, '');

const left = [...html.matchAll(/(?:src|href)="(\.?\/?(?:assets|icons)\/[^"]+)"/g)].map((m) => m[1]);
if (left.length) { console.error('still referenced from outside:', left); process.exit(1); }
const out = `// Generated by scripts/inline-web.mjs from depth-music/public. Do not edit.\nexport default ${JSON.stringify(html)};\n`;
fs.writeFileSync(path.join(here, '..', 'web.js'), out);
console.log(`web.js: ${(out.length / 1024).toFixed(0)} KB`);
